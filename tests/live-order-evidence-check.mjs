import assert from 'node:assert/strict';
import { mkdtempSync, rmSync, writeFileSync, readdirSync, readFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { createLiveSubmissionHold } from '../lib/live-submission-hold.js';
import { createLiveReconciliationHistory } from '../lib/live-reconciliation-history.js';
process.env.KRAKEN_API_KEY = 'offline-fixture-only';
process.env.KRAKEN_API_SECRET = Buffer.from('offline-fixture-only').toString('base64');
let result, tradeResult, tradeFailure = false, calls = 0;
globalThis.fetch = async (url, options) => {
  calls++;
  if (url.endsWith('/GetApiKeyInfo')) return new Response(JSON.stringify({ error: [], result: { apiKey: process.env.KRAKEN_API_KEY, iban: 'FIXTURE ACCOUNT', validUntil: '0', permissions: ['query-open-trades', 'query-closed-trades'] } }));
  assert.ok(['https://api.kraken.com/0/private/QueryOrders', 'https://api.kraken.com/0/private/QueryTrades'].includes(url));
  const isTrade = url.endsWith('/QueryTrades');
  assert.equal(new URLSearchParams(options.body).get('txid'), isTrade ? 'fixture-fill' : 'fixture-order');
  assert.equal(options.redirect, 'error');
  assert.ok(options.signal);
  if (isTrade && tradeFailure) throw Error('offline transport failure');
  return new Response(JSON.stringify({ error: [], result: isTrade ? tradeResult : result }));
};
const scratch = mkdtempSync(join(tmpdir(), 'iost-order-evidence-'));
try {
  const { createKrakenBroker } = await import('../lib/broker/kraken.js');
  const broker = createKrakenBroker({ apiKey: process.env.KRAKEN_API_KEY, apiSecret: process.env.KRAKEN_API_SECRET, ownerId: 'owner' });
  const identity = await broker.getVenueIdentity('owner');
  const holds = createLiveSubmissionHold(scratch);
  const claim = holds.claim('owner', { symbol: 'BTC', side: 'long', size: 1, entry: 50000 }, broker.credentialBinding('owner'), identity.venueAccountBinding);
  assert.equal(holds.acknowledge('owner', 'wrong-client', 'fixture-order').ok, false);
  assert.equal(holds.acknowledge('owner', claim.clientOrderId, 'fixture-order').ok, true);
  assert.equal(holds.acknowledge('owner', claim.clientOrderId, 'different-order').ok, false);
  assert.equal(holds.read('other-owner').ok, false);
  const persisted = createLiveSubmissionHold(scratch).read('owner');
  assert.equal(persisted.hold.venueOrderId, 'fixture-order');
  const { inspectHeldLiveOrder, recordHeldLiveOrderEvidence } = await import('../lib/live-order-evidence.js');
  const observation = { cl_ord_id: claim.clientOrderId, vol: '1.00000000', vol_exec: '0.25', status: 'open', descr: { pair: 'XBTUSD', type: 'buy', ordertype: 'limit', price: '50000.0' } };
  result = { 'fixture-order': observation };
  let review = await inspectHeldLiveOrder(holds, 'owner', broker);
  assert.equal(review.status, 'partial-evidence');
  assert.equal(review.releaseAllowed, false);
  result = { 'fixture-order': { ...observation, trades: ['fixture-fill'], cost: '12500', fee: '12.5' } };
  tradeResult = { 'fixture-fill': { ordertxid: 'fixture-order', pair: 'XXBTZUSD', type: 'buy', vol: '0.25', price: '50000', cost: '12500', fee: '12.5', margin: '0' } };
  const queryStart = calls;
  review = await inspectHeldLiveOrder(holds, 'owner', broker);
  assert.equal(calls - queryStart, 3, 'one identity, order and fill query');
  assert.equal(review.fillEvidence.status, 'fill-totals-matched');
  assert.equal(review.fillEvidence.feesVerified, false);
  assert.equal(review.releaseAllowed, false);
  const history = createLiveReconciliationHistory(join(scratch, 'history'));
  assert.equal((await recordHeldLiveOrderEvidence(holds, 'owner', broker, history)).status, 'recorded');
  assert.equal((await recordHeldLiveOrderEvidence(holds, 'owner', broker, history)).status, 'replay');
  tradeResult['fixture-fill'].price = '51000';
  assert.equal((await recordHeldLiveOrderEvidence(holds, 'owner', broker, history)).status, 'held', 'changed same-fill evidence cannot replace history');
  tradeResult['fixture-fill'].price = '50000';
  tradeResult = {};
  assert.equal((await recordHeldLiveOrderEvidence(holds, 'owner', broker, history)).status, 'held');
  assert.equal((await inspectHeldLiveOrder(holds, 'owner', broker)).fillEvidence.status, 'unknown');
  tradeFailure = true;
  const failureStart = calls;
  assert.equal((await inspectHeldLiveOrder(holds, 'owner', broker)).fillEvidence.status, 'unknown');
  assert.equal(calls - failureStart, 3, 'failed fill query not retried');
  tradeFailure = false;
  assert.equal(review.feesVerified, false);
  result = {};
  assert.equal((await inspectHeldLiveOrder(holds, 'owner', broker)).status, 'unknown');
  for (const change of [{ cl_ord_id: 'different' }, { cl_ord_id: undefined }, { vol_exec: '2' }, { vol_exec: '-1' }, { vol: '2' }, { descr: { ...observation.descr, type: 'sell' } }, { descr: { ...observation.descr, pair: 'ETHUSD' } }, { descr: { ...observation.descr, price: '60000' } }, { status: 'closed' }]) {
    result = { 'fixture-order': { ...observation, ...change } };
    assert.equal((await inspectHeldLiveOrder(holds, 'owner', broker)).status, 'unknown');
  }
  result = { 'fixture-order': { ...observation, status: 'closed', vol_exec: '1' } };
  review = await inspectHeldLiveOrder(holds, 'owner', broker);
  assert.equal(review.status, 'filled-evidence');
  assert.equal(review.releaseAllowed, false);
  const before = calls;
  holds.claim('unacknowledged', { symbol: 'BTC', side: 'long', size: 1 }, 'a'.repeat(64), 'b'.repeat(64));
  assert.equal((await inspectHeldLiveOrder(holds, 'unacknowledged', broker)).status, 'unknown');
  assert.equal(calls, before, 'no guessed venue ID or discovery retry');
  assert.equal(holds.claim('owner', { symbol: 'BTC', side: 'long', size: 1 }, broker.credentialBinding('owner'), identity.venueAccountBinding).ok, false);
  const file = join(scratch, readdirSync(scratch).find(name => name.endsWith('.ack')));
  const ackBefore = readFileSync(file, 'utf8');
  assert.equal(holds.acknowledge('owner', claim.clientOrderId, 'different-order').ok, false);
  assert.equal(readFileSync(file, 'utf8'), ackBefore, 'acknowledgement cannot be overwritten');
  writeFileSync(file, '{broken');
  const callsBeforeCorruption = calls;
  assert.equal((await inspectHeldLiveOrder(holds, 'owner', broker)).status, 'unknown');
  assert.equal(calls, callsBeforeCorruption, 'corrupt evidence cannot cause a query');
  console.log('Held order evidence checks passed; no exchange calls or hold release');
} finally { rmSync(scratch, { recursive: true, force: true }); }
