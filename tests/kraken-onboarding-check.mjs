import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { createCredentialVault } from '../lib/credential-vault.js';
import { createKrakenOnboarding } from '../lib/kraken-onboarding.js';
const server = readFileSync(new URL('../server.js', import.meta.url), 'utf8');
const legacy = server.slice(server.indexOf("app.put('/api/account/kraken'"), server.indexOf('// ---- free IOST mainnet wallet'));
assert.doesNotMatch(legacy, /createKrakenBroker|setUserKrakenKey/);
assert.match(legacy, /req.userAgent/);
assert.match(legacy, /persistCredentialReplacement/);
const v = createCredentialVault({ keys: { v1: Buffer.alloc(32, 12).toString('base64') }, activeKeyId: 'v1' });
let clock = 1000, enabled = true, verified = true, writes = 0;
const service = createKrakenOnboarding({ vault: () => v, enabled: () => enabled, now: () => clock, verify: async (_keys, options) => {
  assert.equal(options.requireReadOnly, true);
  return { accountHealth: 'reachable', profile: verified ? 'read-only' : 'trade-capable', permissionStatus: 'observed-allowed-permissions' };
}, persist: (u, blob, status) => { writes++; u.krakenKey = blob; u.krakenKeyStatus = status; } });
const user = { id: 'fixture-owner', passHash: 'fixture-password-state' };
const input = { apiKey: 'fixtureKeyForTestingOnly', apiSecret: Buffer.alloc(64, 6).toString('base64'), consent: true };
enabled = false; assert.equal((await service.preview(user, 'session', input)).ok, false); enabled = true;
verified = false; assert.equal((await service.preview(user, 'session', input)).ok, false); verified = true;
assert.equal((await service.preview(user, 'session', { ...input, ownerId: 'other' })).ok, false);
const plan = await service.preview(user, 'session', input);
assert.equal(plan.ok, true); assert.equal(writes, 0); assert.equal(user.krakenKey, undefined);
assert(!JSON.stringify(plan).includes(input.apiKey)); assert(!JSON.stringify(plan).includes(input.apiSecret));
assert.equal(service.commit(user, 'other-session', { token: plan.token, confirmed: true }).ok, false);
assert.equal(service.commit({ id: 'other-owner' }, 'session', { token: plan.token, confirmed: true }).ok, false);
assert.equal(service.commit(user, 'session', { token: plan.token, confirmed: true }).ok, true);
assert.equal(writes, 1); assert.equal(user.krakenKeyStatus.permissionsVerified, false);
assert.equal(service.commit(user, 'session', { token: plan.token, confirmed: true }).ok, false);
assert.equal((await service.preview(user, 'session', input)).ok, false);
delete user.krakenKey;
const expired = await service.preview(user, 'session', input); clock += 120001;
assert.equal(service.commit(user, 'session', { token: expired.token, confirmed: true }).ok, false);
const changed = await service.preview(user, 'session', input); user.passHash = 'new-password';
assert.equal(service.commit(user, 'session', { token: changed.token, confirmed: true }).ok, false);
const disablePlan = await service.preview(user, 'session', input); enabled = false;
assert.equal(service.commit(user, 'session', { token: disablePlan.token, confirmed: true }).ok, false); enabled = true;
const broken = createKrakenOnboarding({ vault: () => v, enabled: () => true, verify: async () => ({ accountHealth: 'reachable', profile: 'read-only', permissionStatus: 'observed-allowed-permissions' }), persist: () => { throw Error('private filesystem detail'); } });
const brokenPlan = await broken.preview(user, 'session', input);
const failedSave = broken.commit(user, 'session', { token: brokenPlan.token, confirmed: true });
assert.equal(failedSave.ok, false); assert.equal(user.krakenKey, undefined);
assert.doesNotMatch(JSON.stringify(failedSave), /private filesystem/);
console.log('Secure Kraken onboarding checks passed');
