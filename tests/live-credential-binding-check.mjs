import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
process.env.KRAKEN_API_KEY = 'offline-environment-fixture';
process.env.KRAKEN_API_SECRET = 'offline-environment-secret';
let calls = 0;
globalThis.fetch = async () => { calls++; throw Error('network disabled'); };
const { createKrakenBroker } = await import('../lib/broker/kraken.js');
const keys = { apiKey: 'offline-key', apiSecret: 'offline-secret', ownerId: 'owner-a' };
const broker = createKrakenBroker(keys);
const binding = broker.credentialBinding('owner-a');
assert.match(binding, /^[a-f0-9]{64}$/);
assert.equal(createKrakenBroker(keys).credentialBinding('owner-a'), binding);
assert.equal(broker.credentialBinding('owner-b'), null);
assert.notEqual(createKrakenBroker({ ...keys, apiKey: 'replacement' }).credentialBinding('owner-a'), binding);
assert.notEqual(createKrakenBroker({ ...keys, apiSecret: 'replacement' }).credentialBinding('owner-a'), binding);
assert.equal(createKrakenBroker({ apiKey: 'partial', ownerId: 'owner-a' }).configured, false, 'partial override cannot borrow environment secret');
assert.equal(createKrakenBroker({ ownerId: 'owner-a' }).credentialBinding('owner-a'), null, 'environment credentials are not a per-user connection');
const hold = { credentialBinding: binding, venueOrderId: 'fixture-order', clientOrderId: 'fixture-client', order: { symbol: 'BTC', side: 'long', size: '1', entry: '50000' } };
assert.equal((await broker.getOrderEvidence(hold, 'owner-b')).ok, false);
assert.equal((await broker.getOrderEvidence({ ...hold, credentialBinding: undefined }, 'owner-a')).ok, false);
assert.equal((await createKrakenBroker({ ...keys, apiKey: 'replacement' }).getOrderEvidence(hold, 'owner-a')).ok, false);
assert.equal(calls, 0, 'binding failures happen before any exchange request');
const server = readFileSync(new URL('../server.js', import.meta.url), 'utf8');
const execute = server.slice(server.indexOf('async function executeLiveOrder'), server.indexOf("app.post('/api/trade/live'"));
assert.ok(execute.indexOf('if (!credentialBinding)') < execute.indexOf('kraken.getAccount()'), 'server checks binding before venue reads');
assert.ok(execute.includes('entry }, credentialBinding, venueIdentity.venueAccountBinding)'), 'server persists connection and venue bindings');
console.log('Owner and credential binding checks passed without network access');
