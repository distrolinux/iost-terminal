import assert from 'node:assert/strict';
import { mkdtempSync, writeFileSync, chmodSync, symlinkSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { configuredCredentialVault } from '../lib/credential-vault.js';
import { credentialStorageStatus, createCredentialMaintenance } from '../lib/credential-maintenance.js';
import { setUserKrakenKey } from '../lib/keys.js';
const dir = mkdtempSync(join(tmpdir(), 'iost-vault-file-'));
const file = join(dir, 'vault.json');
const names = ['IOST_CREDENTIAL_VAULT_FILE', 'IOST_CREDENTIAL_VAULT_KEYS', 'IOST_CREDENTIAL_VAULT_ACTIVE_KEY_ID'];
const saved = names.map(n => process.env[n]);
try {
  names.forEach(n => delete process.env[n]);
  process.env.IOST_CREDENTIAL_VAULT_FILE = file;
  assert.throws(() => configuredCredentialVault(), /^Error: vault configuration unavailable$/);
  const fixture = JSON.stringify({ activeKeyId: 'file-key', keys: { 'file-key': Buffer.alloc(32, 83).toString('base64') } });
  writeFileSync(file, fixture, { mode: 0o600 });
  const vault = configuredCredentialVault();
  assert.equal(vault.activeKeyId, 'file-key');
  const envelope = vault.seal('fixture-owner', 'kraken', 'fixture-value');
  assert.equal(vault.open('fixture-owner', 'kraken', envelope), 'fixture-value');
  const user = { id: 'fixture-owner' };
  assert.equal(setUserKrakenKey(user, 'fixture-key', 'fixture-secret').ok, true);
  assert.equal(credentialStorageStatus(user).migrationNeeded, false);
  writeFileSync(file, JSON.stringify({ activeKeyId: 'rotated-file-key', keys: { 'file-key': Buffer.alloc(32, 83).toString('base64'), 'rotated-file-key': Buffer.alloc(32, 89).toString('base64') } }));
  const service = createCredentialMaintenance({ backup: () => {}, persist: (u, blob) => { u.krakenKey = blob; } });
  assert.equal(credentialStorageStatus(user).migrationNeeded, true);
  const plan = service.preview(user, 'fixture-session');
  assert.equal(service.apply(user, 'fixture-session', plan.token, true).ok, true);
  assert.equal(user.krakenKey.keyId, 'rotated-file-key');
  writeFileSync(file, fixture);
  chmodSync(file, 0o400); assert.equal(configuredCredentialVault().activeKeyId, 'file-key');
  chmodSync(file, 0o644); assert.throws(() => configuredCredentialVault(), /vault configuration unavailable/);
  chmodSync(file, 0o600);
  process.env.IOST_CREDENTIAL_VAULT_KEYS = '{}';
  assert.throws(() => configuredCredentialVault(), /vault configuration unavailable/, 'ambiguous source must not fall back');
  delete process.env.IOST_CREDENTIAL_VAULT_KEYS;
  const link = join(dir, 'symlink.json'); symlinkSync(file, link);
  process.env.IOST_CREDENTIAL_VAULT_FILE = link;
  assert.throws(() => configuredCredentialVault(), /vault configuration unavailable/);
  process.env.IOST_CREDENTIAL_VAULT_FILE = dir;
  assert.throws(() => configuredCredentialVault(), /vault configuration unavailable/);
  process.env.IOST_CREDENTIAL_VAULT_FILE = 'relative.json';
  assert.throws(() => configuredCredentialVault(), /vault configuration unavailable/);
  process.env.IOST_CREDENTIAL_VAULT_FILE = file;
  writeFileSync(file, 'x'.repeat(8193));
  assert.throws(() => configuredCredentialVault(), /vault configuration unavailable/);
  writeFileSync(file, '{invalid-fixture');
  assert.throws(() => configuredCredentialVault(), /^Error: vault configuration unavailable$/);
} finally {
  names.forEach((n, i) => saved[i] === undefined ? delete process.env[n] : process.env[n] = saved[i]);
  rmSync(dir, { recursive: true, force: true });
}
console.log('Protected vault file checks passed');
