import assert from 'node:assert/strict';
import { mkdtempSync, rmSync, readFileSync, readdirSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { configureKrakenCoordination, coordinateKrakenRequest } from '../lib/kraken-request-coordinator.js';
const root = mkdtempSync(join(tmpdir(), 'iost-recovery-reader-'));
configureKrakenCoordination(root);
const original = { ownerId: 'owner', apiKey: 'fixture-trading', apiSecret: 'fixture-secret' };
const recovery = { apiKey: 'fixture-recovery', apiSecret: 'fixture-read-secret' };
let recoveryInfo = { apiKey: recovery.apiKey, iban: 'FIXTURE ACCOUNT', validUntil: '0', permissions: ['query-open-trades', 'query-closed-trades'] };
let queries = 0;
let orderResult = { 'fixture-order': { cl_ord_id: 'fixture-client', status: 'open', vol: '1', vol_exec: '0', descr: { pair: 'XBTUSD', type: 'buy', ordertype: 'limit', price: '50000' } } };
globalThis.fetch = async (url, options) => {
  queries++;
  assert.ok(url.endsWith('/GetApiKeyInfo') || url.endsWith('/QueryOrders'));
  const key = options.headers['API-Key'];
  if (url.endsWith('/GetApiKeyInfo')) return new Response(JSON.stringify({ error: [], result: key === original.apiKey ? { ...recoveryInfo, apiKey: original.apiKey } : recoveryInfo }));
  assert.equal(key, recovery.apiKey);
  return new Response(JSON.stringify({ error: [], result: orderResult }));
};
try {
  const { createKrakenBroker } = await import('../lib/broker/kraken.js');
  const broker = createKrakenBroker(original);
  const identity = await broker.getVenueIdentity('owner');
  const hold = { credentialBinding: broker.credentialBinding('owner'), venueAccountBinding: identity.venueAccountBinding, venueOrderId: 'fixture-order', clientOrderId: 'fixture-client', order: { symbol: 'BTC', side: 'long', size: '1', entry: '50000' } };
  await assert.rejects(coordinateKrakenRequest(original.apiKey, async () => { throw Error('unknown submission'); }, Date.now, 'AddOrder'));
  const lock = readdirSync(root).find(name => name.endsWith('.lock'));
  const before = readFileSync(join(root, lock), 'utf8');
  const report = await broker.readRecoveryOrder(hold, 'owner', recovery);
  assert.equal(report.status, 'open-evidence'); assert.equal(report.releaseAllowed, false);
  assert.equal(readFileSync(join(root, lock), 'utf8'), before, 'trading request lock remains untouched');
  assert.ok(!JSON.stringify(report).includes(recovery.apiKey));
  const count = queries;
  assert.equal((await broker.readRecoveryOrder(hold, 'other', recovery)).status, 'unknown');
  assert.equal((await broker.readRecoveryOrder(hold, 'owner', original)).status, 'unknown');
  assert.equal(queries, count);
  recoveryInfo = { ...recoveryInfo, iban: 'WRONG ACCOUNT' };
  const beforeWrong = queries;
  assert.equal((await broker.readRecoveryOrder(hold, 'owner', recovery)).status, 'unknown');
  assert.equal(queries - beforeWrong, 1, 'wrong account cannot query an order');
  recoveryInfo = { ...recoveryInfo, iban: 'FIXTURE ACCOUNT', permissions: ['query-open-trades', 'query-closed-trades', 'modify-trades'] };
  const beforePermission = queries;
  assert.equal((await broker.readRecoveryOrder(hold, 'owner', recovery)).status, 'unknown');
  assert.equal(queries - beforePermission, 1, 'trading-capable recovery key cannot query an order');
  recoveryInfo = { ...recoveryInfo, permissions: ['query-open-trades', 'query-closed-trades'] };
  orderResult = {};
  assert.equal((await broker.readRecoveryOrder(hold, 'owner', recovery)).status, 'unknown', 'absence is not rejection');
  assert.equal(readFileSync(join(root, lock), 'utf8'), before);
  console.log('Separate read-only recovery credential, same-account check and unchanged trading lock passed');
} finally { rmSync(root, { recursive: true, force: true }); }
