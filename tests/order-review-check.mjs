import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { buildOrderReview } from '../lib/order-review.js';
const input = { symbol: 'IOST', quantity: '100', limitPrice: '0.001', protectiveStop: '0.0009', assumedFeeBps: '25' };
const original = JSON.stringify(input);
const result = buildOrderReview(input, { maxOrderUsd: '50', now: 1000 });
assert.equal(result.amounts.notionalUsd, '0.10000000');
assert.equal(result.amounts.assumedFeeUsd, '0.00025000');
assert.equal(result.amounts.assumedTotalUsd, '0.10025000');
assert.equal(result.amounts.lossToStopBeforeFeesUsd, '0.01000000');
assert.equal(result.expiresAt, 61000);
assert.equal(result.approval.expiresAt, null);
assert.equal(result.decision, 'not-authorized');
assert.equal(JSON.stringify(input), original);
assert(Object.values(result.execution).every(v => v === false));
const unknown = buildOrderReview({ ...input, assumedFeeBps: '', protectiveStop: '' });
assert.equal(unknown.amounts.assumedTotalUsd, null);
assert.equal(unknown.policy.notionalCap, 'unknown');
assert.equal(unknown.evidence.protectiveStop, 'missing');
assert.equal(buildOrderReview(input, { maxOrderUsd: '0.01' }).policy.notionalCap, 'exceeds-configured-cap');
for (const quantity of ['-1', '0', '1e3', '0.123456789', 'Infinity', 1, '10000000000']) assert.throws(() => buildOrderReview({ ...input, quantity }));
for (const extra of [{ ownerId: 'other' }, { approved: true }, { side: 'sell' }, { provider: 'other' }]) assert.throws(() => buildOrderReview({ ...input, ...extra }));
assert.throws(() => buildOrderReview({ ...input, protectiveStop: '0.002' }));
assert.throws(() => buildOrderReview({ ...input, assumedFeeBps: '1001' }));
assert.equal(buildOrderReview({ symbol: 'BTC', quantity: '0.00000001', limitPrice: '0.00000001' }).amounts.notionalUsd, '0.00000001');
const server = readFileSync(new URL('../server.js', import.meta.url), 'utf8');
const route = server.slice(server.indexOf("app.post('/api/exchange-connections/order-review'"), server.indexOf('const credentialMaintenance ='));
assert.match(route, /requireUser/);
assert.match(route, /req.userAgent \|\| !req.session\?\.userId \|\| req.agentKey/);
assert.match(route, /private, no-store/);
assert.doesNotMatch(route, /getUserKrakenKeys|addProposal|claimForExecution|brokerForUser|logLiveEvent/);
console.log('Read-only order draft checks passed');
