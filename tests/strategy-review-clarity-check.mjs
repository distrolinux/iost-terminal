import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { buildOrderReview } from '../lib/order-review.js';
import { strategyReviewSections } from '../public/js/strategy-review.js';
import { formatDraftUsd } from '../public/js/draft-format.js';
assert.equal(formatDraftUsd('50000.00000000'), '$50,000.00 USD');
assert.equal(formatDraftUsd('0.00000001'), '$0.00000001 USD');
assert.equal(formatDraftUsd('0.00120000'), '$0.0012 USD');
assert.equal(formatDraftUsd('9007199254740993.12000000'), '$9,007,199,254,740,993.12 USD');
assert.equal(formatDraftUsd('0.00000000'), '$0.00 USD');
for (const v of [null, undefined, 0, 'NaN', '1e3', '-1', '<script>', '1.123456789']) assert.equal(formatDraftUsd(v), 'Unknown — not verified');
const review = buildOrderReview({ symbol: 'BTC', quantity: '0.001', limitPrice: '50000' }, { maxOrderUsd: '25' });
const before = JSON.stringify(review);
const rows = r => Object.fromEntries(strategyReviewSections(r).flatMap(s => s.rows));
let result = rows(review);
assert.equal(strategyReviewSections(review).length, 4);
assert.match(result.Mode, /draft only.*locked/);
assert.match(result['Cap check'], /Exceeds cap/);
assert.equal(result['Protective exit'], 'No stop drafted');
assert.match(result['Assumed fee'], /Unknown/);
assert.match(result['Owner approval'], /Not requested/);
assert.equal(JSON.stringify(review), before);
const complete = buildOrderReview({ symbol: 'IOST', quantity: '10', limitPrice: '1', protectiveStop: '0.9', assumedFeeBps: '0' }, { maxOrderUsd: '25' });
complete.market = { status: 'public-checks-passed' };
result = rows(complete);
assert.match(result['Protective exit'], /not armed/);
assert.match(result['Assumed fee'], /0\.00.*assumption/);
assert.match(result['Cap check'], /not spending authorization/);
assert.match(result['Market evidence'], /execution not authorized/);
assert.match(result['Loss to drafted stop'], /not a maximum loss guarantee/);
assert.match(rows({})['Configured notional cap'], /Unknown/);
const ui = readFileSync(new URL('../public/js/order-review.js', import.meta.url), 'utf8');
assert.match(ui, /strategyReviewSections/);
assert.match(ui, /title\.textContent = group.title/);
assert.match(ui, /dd\.textContent = value/);
assert.match(ui, /Review expired/);
assert.doesNotMatch(ui, /localStorage|sessionStorage|\/trade|\/approve/);
console.log('Strategy review clarity checks passed');
