import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
const server = readFileSync(new URL('../server.js', import.meta.url), 'utf8');
assert.match(server, /consumeCredentialProof/, 'credential mutations must consume fresh authentication proof');
const { issueCredentialProof, consumeCredentialProof } = await import('../lib/credential-reauth.js');
const user = { id: 'fixture-owner', passHash: 'fixture-hash', totpEnabled: false };
const session = { userId: user.id };
const token = issueCredentialProof(session, user, 'connect', 1000);
assert.equal(consumeCredentialProof(session, user, 'disconnect', token, 1001), false);
const good = issueCredentialProof(session, user, 'connect', 1000);
assert.equal(consumeCredentialProof(session, user, 'connect', good, 1001), true);
assert.equal(consumeCredentialProof(session, user, 'connect', good, 1002), false);
const expired = issueCredentialProof(session, user, 'connect', 1000);
assert.equal(consumeCredentialProof(session, user, 'connect', expired, 121000), false);
const changed = issueCredentialProof(session, user, 'connect', 1000); user.passHash = 'changed';
assert.equal(consumeCredentialProof(session, user, 'connect', changed, 1001), false);
const mfa = issueCredentialProof(session, user, 'connect', 1000); user.totpEnabled = true;
assert.equal(consumeCredentialProof(session, user, 'connect', mfa, 1001), false);
assert.throws(() => issueCredentialProof(session, user, 'trade', 1000));
const race = issueCredentialProof(session, user, 'disconnect', 1000);
const copy = structuredClone(session);
assert.equal(consumeCredentialProof(session, user, 'disconnect', race, 1001), true);
assert.equal(consumeCredentialProof(copy, user, 'disconnect', race, 1001), false);
const replacement = issueCredentialProof(session, user, 'disconnect', 1000);
user.krakenKey = { version: 1, data: 'different-fixture' };
assert.equal(consumeCredentialProof(session, user, 'disconnect', replacement, 1001), false);
console.log('Credential reauthentication checks passed');
