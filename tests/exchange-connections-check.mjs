import assert from 'node:assert/strict';
import './trading-workspace-entry-check.mjs';
import './kraken-connection-verification-check.mjs';
import './credential-vault-check.mjs';
import './credential-maintenance-check.mjs';
import './credential-vault-file-check.mjs';
import { readFileSync } from 'node:fs';
import { buildExchangeConnections } from '../lib/exchange-connections.js';
const empty = buildExchangeConnections();
assert.equal(empty.launchDecision, 'locked');
assert.equal(empty.connections[0].configured, false);
assert.equal(empty.executionAuthority, 'none');
const input = { kraken: { configured: true, permissionsVerified: 'true', apiKey: 'fixture-only', maskedKey: 'fixture-mask', accountId: 'private-fixture' }, readiness: { decision: 'allow-controlled-canary' } };
const before = JSON.stringify(input);
const status = buildExchangeConnections(input);
assert.equal(status.connections[0].permissionsVerified, false);
assert.equal(status.connections[0].accountHealth, 'not-probed');
assert.equal(status.launchDecision, 'canary-review-required');
assert.equal(status.execution.attempted, false);
assert.equal(JSON.stringify(input), before);
assert.ok(!JSON.stringify(status).includes('fixture'));
assert.ok(Object.values(status.boundaries).every(v => v === false));
assert.equal(buildExchangeConnections({ kraken: { permissionsVerified: true } }).connections[0].permissionsVerified, false);
const server = readFileSync(new URL('../server.js', import.meta.url), 'utf8');
const route = server.slice(server.indexOf("app.get('/api/exchange-connections'"), server.indexOf("app.get('/api/public-live-readiness'"));
assert.match(route, /requireUser/);
assert.match(route, /req.userAgent \|\| !req.session\?\.userId/);
assert.match(route, /private, no-store/);
assert.match(route, /auth.findById\(req.session.userId\)/);
const ui = readFileSync(new URL('../public/js/app.js', import.meta.url), 'utf8');
const view = ui.slice(ui.indexOf('async function renderExchangeConnections'), ui.indexOf('// ---------------- Asset Intelligence Workspace'));
assert.match(view, /post\('\/api\/exchange-connections\/kraken\/verify'/);
assert.doesNotMatch(view, /\/api\/live\/.*approve|AddOrder|\/api\/trade/);
assert.match(view, /Not integrated/);
assert.match(view, /replaceChildren/);
console.log('Exchange connections checks passed');
