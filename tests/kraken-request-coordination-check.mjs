import assert from 'node:assert/strict';
import { coordinateKrakenRequest } from '../lib/kraken-request-coordinator.js';
let release;
const gate = new Promise(resolve => { release = resolve; });
const events = [];
const a = coordinateKrakenRequest('fixture-key', async nonce => { events.push(['a', nonce]); await gate; }, () => 1000);
const b = coordinateKrakenRequest('fixture-key', async nonce => { events.push(['b', nonce]); }, () => 999);
await coordinateKrakenRequest('other-fixture-key', async () => { events.push(['other']); }, () => 1000);
assert.deepEqual(events.map(e => e[0]), ['a', 'other']);
release(); await Promise.all([a, b]);
assert.ok(BigInt(events[2][1]) > BigInt(events[0][1]));
await assert.rejects(coordinateKrakenRequest('fixture-key', async () => { throw Error('fixture'); }));
await coordinateKrakenRequest('fixture-key', async () => { events.push(['after-failure']); });
assert.equal(events.at(-1)[0], 'after-failure');
process.env.KRAKEN_API_KEY = 'offline-only'; process.env.KRAKEN_API_SECRET = 'offline-only';
let active = 0, peak = 0, lastNonce = 0n, count = 0;
globalThis.fetch = async (url, options) => {
  assert.ok(['https://api.kraken.com/0/private/Balance', 'https://api.kraken.com/0/private/GetApiKeyInfo'].includes(url));
  active++; count++; peak = Math.max(peak, active);
  const nonce = BigInt(new URLSearchParams(options.body).get('nonce'));
  assert.ok(nonce > lastNonce); lastNonce = nonce;
  await new Promise(resolve => setTimeout(resolve, 1));
  active--;
  return new Response(JSON.stringify({ error: [], result: url.endsWith('Balance') ? { ZUSD: '100' } : { permissions: ['query-funds'] } }));
};
const { createKrakenBroker } = await import('../lib/broker/kraken.js');
const { verifyKrakenConnection } = await import('../lib/kraken-connection-verification.js');
const keys = { apiKey: 'integration-fixture', apiSecret: 'integration-fixture-secret' };
const results = await Promise.all([createKrakenBroker(keys).getAccount(), createKrakenBroker(keys).getAccount(), verifyKrakenConnection(keys)]);
assert.equal(results[0].ok, true); assert.equal(results[1].ok, true);
assert.equal(results[2].accountHealth, 'reachable');
assert.equal(count, 4); assert.equal(peak, 1, 'broker instances and verifier share one request lane');
console.log('Shared-key serialization, independent keys and failure recovery passed');
